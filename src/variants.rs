use rand::seq::SliceRandom;

macro_rules! message_variants {
    ($name:ident, $($variant:expr),+ $(,)?) => {
        pub fn $name() -> &'static str {
            static VARIANTS: &[&str] = &[$($variant),+];
            VARIANTS.choose(&mut rand::thread_rng()).unwrap_or(&VARIANTS[0])
        }
    }
}

